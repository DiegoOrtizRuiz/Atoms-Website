create table public.deals (
  id text primary key,
  source_tab text,
  source_row integer,
  vertical text,
  client text,
  market text,
  city text,
  state text,
  state_inferred boolean not null default false,
  address text,
  stage public.deal_stage not null default 'Needs review',
  stage_raw text,
  stage_entered_at timestamptz not null default now(),
  bldg_sf numeric,
  list_price numeric,
  lot_sf numeric,
  price_per_sf numeric generated always as (
    round(list_price / nullif(bldg_sf, 0), 2)
  ) stored,
  price_per_lot_sf numeric generated always as (
    round(list_price / nullif(lot_sf, 0), 2)
  ) stored,
  broker text,
  broker_phone text,
  notes text,
  weekly_note text,
  show_in_weekly boolean not null default false,
  attributes jsonb not null default '{}'::jsonb
    check (jsonb_typeof(attributes) = 'object'),
  attributes_raw jsonb not null default '{}'::jsonb
    check (jsonb_typeof(attributes_raw) = 'object'),
  field_provenance jsonb not null default '{}'::jsonb
    check (jsonb_typeof(field_provenance) = 'object'),
  notes_extracted jsonb,
  needs_review boolean not null default false,
  review_reasons text[] not null default '{}',
  version integer not null default 1,
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles (id) on delete set null,
  constraint deals_source_row_positive check (source_row is null or source_row > 0),
  constraint deals_version_positive check (version > 0)
);


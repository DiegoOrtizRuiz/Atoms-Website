create or replace function public.current_profile()
returns public.profiles
language sql
stable
security definer
set search_path = ''
as $$
  select p
  from public.profiles as p
  where p.id = auth.uid();
$$;

create or replace function public.current_role()
returns public.user_role
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when (public.current_profile()).active then (public.current_profile()).role
    else null
  end;
$$;

create or replace function public.current_user_active()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((public.current_profile()).active, false);
$$;

revoke all on function public.current_profile() from public;
revoke all on function public.current_role() from public;
revoke all on function public.current_user_active() from public;
grant execute on function public.current_profile() to authenticated;
grant execute on function public.current_role() to authenticated;
grant execute on function public.current_user_active() to authenticated;

create or replace function public.prepare_deal_update()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.version is distinct from old.version then
    raise exception using
      errcode = 'P0001',
      message = 'Deal version is managed by the database.';
  end if;

  new.version := old.version + 1;
  new.updated_at := now();
  new.updated_by := auth.uid();

  if new.stage is distinct from old.stage then
    new.stage_entered_at := now();
  end if;

  return new;
end;
$$;

create or replace function public.record_deal_history()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  old_json jsonb := to_jsonb(old);
  new_json jsonb := to_jsonb(new);
  changed_field record;
begin
  for changed_field in
    select key
    from jsonb_each(new_json)
    where value is distinct from old_json -> key
  loop
    insert into public.deal_history (
      deal_id,
      changed_by,
      changed_at,
      field,
      old_value,
      new_value
    )
    values (
      new.id,
      auth.uid(),
      new.updated_at,
      changed_field.key,
      old_json -> changed_field.key,
      new_json -> changed_field.key
    );
  end loop;

  return null;
end;
$$;

create or replace function public.enforce_provenance_permissions()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
declare
  provenance_key text;
  new_status text;
  old_status text;
begin
  if new.field_provenance is not distinct from old.field_provenance then
    return new;
  end if;

  for provenance_key, new_status in
    select key, value
    from jsonb_each_text(new.field_provenance)
  loop
    if new_status not in ('assumed', 'llm_suggested', 'confirmed') then
      raise exception using
        errcode = '22023',
        message = 'Field provenance must be assumed, llm_suggested, or confirmed.';
    end if;

    old_status := old.field_provenance ->> provenance_key;
    if new_status = 'confirmed' and old_status is distinct from 'confirmed' then
      if public.current_role() not in ('admin', 'acq_lead') then
        raise exception using
          errcode = '42501',
          message = 'This role cannot confirm assumptions.';
      end if;

      if public.current_role() = 'acq_lead'
        and not (new.vertical = any ((public.current_profile()).verticals))
      then
        raise exception using
          errcode = '42501',
          message = 'Acquisition leads can only confirm deals in their verticals.';
      end if;
    end if;
  end loop;

  return new;
end;
$$;

create trigger deals_before_update
before update on public.deals
for each row
execute function public.prepare_deal_update();

create trigger deals_provenance_before_update
before update on public.deals
for each row
execute function public.enforce_provenance_permissions();

create trigger deals_after_update
after update on public.deals
for each row
execute function public.record_deal_history();

create view public.v_stage_rollup
with (security_invoker = true)
as
select
  vertical,
  market,
  stage,
  count(*)::bigint as deal_count,
  round(
    avg(extract(epoch from (now() - stage_entered_at)) / 86400)::numeric,
    1
  ) as avg_days_in_stage
from public.deals
group by vertical, market, stage;


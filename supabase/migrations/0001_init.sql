create policy "permitted roles update deals"
on public.deals for update
to authenticated
using (
  public.current_user_active()
  and (
    public.current_role() = 'admin'
    or (
      public.current_role() = 'acq_lead'
      and vertical = any ((public.current_profile()).verticals)
    )
    or (
      public.current_role() = 'analyst'
      and client = any ((public.current_profile()).clients)
    )
  )
)
with check (
  public.current_user_active()
  and (
    public.current_role() = 'admin'
    or (
      public.current_role() = 'acq_lead'
      and vertical = any ((public.current_profile()).verticals)
    )
    or (
      public.current_role() = 'analyst'
      and client = any ((public.current_profile()).clients)
    )
  )
);

